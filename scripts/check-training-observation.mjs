import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const policy = await import('../src/components/atlas3d/render-policy.ts');
assert.equal(typeof policy.presentationBackground, 'function', 'observation backgrounds must be implemented');
assert.equal(policy.presentationBackground('light'), 0xeeefeb);
assert.equal(policy.presentationBackground('dark'), 0x17242c);
assert.equal(policy.presentationBackground(undefined), policy.presentationBackground('light'));
const observation = await import('../src/lib/clinical/training-observation.ts');
for (const group of ['glutes','hamstrings','calves','lats_teres','upper_back_traps']) assert.equal(observation.preferredTrainingView(group), 'back-oblique');
for (const group of ['chest','quads_adductors','abs_obliques','deltoids','biceps_forearm','triceps']) assert.equal(observation.preferredTrainingView(group), 'front-oblique');
const manifest = JSON.parse(readFileSync(new URL('../public/anatomy/3d/manifest.json',import.meta.url)));
const hip = manifest.structures.find(s=>s.english==='Gluteus maximus muscle' && s.side==='left');
assert(hip);
assert.match(observation.sourceStructureLabel(hip), /trái/);
const input={area:'hip',hiddenIds:new Set(),bones:true,selectedId:hip.id,isolatedId:null};
assert.equal(observation.visibleObservationSelection(manifest.structures,input)?.id,hip.id);
assert.equal(observation.visibleObservationSelection(manifest.structures,{...input,area:'upper'}),undefined);
assert.equal(observation.visibleObservationSelection(manifest.structures,{...input,hiddenIds:new Set([hip.id])}),undefined);
assert.equal(observation.visibleObservationSelection(manifest.structures,{...input,isolatedId:'different'}),undefined);
const bone=manifest.structures.find(s=>s.layer==='bone'&&s.areas.includes('hip'));
assert(bone);
assert.equal(observation.visibleObservationSelection(manifest.structures,{...input,selectedId:bone.id,bones:false}),undefined);
assert.equal(observation.visibleObservationSelection(manifest.structures,{...input,selectedId:'invalid'}),undefined);
const heads=manifest.structures.filter(s=>/biceps femoris/i.test(s.english));
assert.equal(new Set(heads.map(observation.sourceStructureLabel)).size,heads.length,'source labels distinguish long/short heads');
console.log('Training observation: backgrounds, preferred views, source labels, region/layer/isolation selection passed.');

// Resolve this existing extensionless TS import for the Node-only method check.
const {registerHooks} = await import('node:module');
const hook = registerHooks({resolve(specifier, context, nextResolve) {
  if (specifier === './render-policy' && context.parentURL?.endsWith('/studio-renderer.ts')) return nextResolve('./render-policy.ts', context);
  return nextResolve(specifier, context);
}});
const {StudioRenderer}=await import('../src/components/atlas3d/studio-renderer.ts');
const {Scene}=await import('three');
const fixture={scene:new Scene(),renderer:{setClearColor() {}}};
StudioRenderer.prototype.setPresentation.call(fixture,'dark');
assert(fixture.scene.background?.isColor,'presentation uses a scene background to clear in the active target color space');
assert.equal(fixture.scene.background.getHex(),policy.presentationBackground('dark'));
StudioRenderer.prototype.setPresentation.call(fixture,'light');
assert.equal(fixture.scene.background.getHex(),policy.presentationBackground('light'));
hook.deregister();
console.log('Composer background color-space regression passed.');
const stateHelpers=await import('../src/components/training/observation-state.ts');
let state=stateHelpers.initialObservation('exercise-a/all','back-oblique');
state={...state,selectedId:hip.id,isolatedId:hip.id,command:{type:'focus',revision:1}};
assert.equal(stateHelpers.reconcileObservation(state,'exercise-a/all','back-oblique',new Set([hip.id])),state,'valid state stays referentially stable');
const hidden=stateHelpers.reconcileObservation(state,'exercise-a/all','back-oblique',new Set());
assert.equal(hidden.isolatedId,null);assert.equal(hidden.selectedId,null);assert.equal(hidden.command.type,'back-oblique');
const next=stateHelpers.reconcileObservation(state,'exercise-b/all','front-oblique',new Set([hip.id]));
assert.equal(next.isolatedId,null);assert.equal(next.selectedId,null);assert.equal(next.command.type,'front-oblique');
const back=stateHelpers.reconcileObservation(next,'exercise-a/all','back-oblique',new Set([hip.id]));
assert.equal(back.isolatedId,null);assert.equal(back.selectedId,null);assert.equal(back.command.type,'back-oblique');
console.log('Observation state: hidden isolation exits, context transitions reset without reviving prior state, stable valid camera commands passed.');
